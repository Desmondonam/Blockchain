// Generate src/abi/DocumentRegistry.ts from Foundry's build output.
// The ABI is GENERATED, never hand-edited, so it can't drift from the contract.
// `as const` lets viem infer exact argument and return types from the ABI.
import { readFileSync, writeFileSync } from "node:fs";

const artifact = JSON.parse(
  readFileSync(new URL("../../contracts/out/DocumentRegistry.sol/DocumentRegistry.json", import.meta.url)),
);
const out = new URL("../src/abi/DocumentRegistry.ts", import.meta.url);
writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/export-abi.mjs from contracts/out. Do not edit.\n` +
    `export const documentRegistryAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
);
console.log(`wrote ${artifact.abi.length} ABI entries to ${out.pathname}`);
